def toolbar_icon(master, name, color, scale=1.0):
    """Render an outline toolbar icon at the current display scale."""
    size = max(24, round(24 * scale))
    scale = size / 24
    segments = [(a, b) for path in _PATHS[name] for a, b in zip(path, path[1:])]
    result = tk.PhotoImage(master=master, width=size, height=size)

    def on_stroke(x, y):
        for (ax, ay), (bx, by) in segments:
            dx, dy = bx - ax, by - ay
            position = max(0, min(1, ((x - ax) * dx + (y - ay) * dy) / (dx * dx + dy * dy)))
            if (x - ax - position * dx) ** 2 + (y - ay - position * dy) ** 2 <= 0.85 ** 2:
                return True
        return False

    for y in range(size):
        start = None
        for x in range(size + 1):
            filled = x < size and on_stroke((x + 0.5) / scale, (y + 0.5) / scale)
            if filled and start is None:
                start = x
            elif not filled and start is not None:
                result.put(color, to=(start, y, x, y + 1))
                start = None
    return result
